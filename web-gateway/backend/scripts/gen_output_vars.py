#!/usr/bin/env python3
"""Generate the Output_vars option list of one WBM code version.

WBM accepts an output variable name only if it is
  (a) in WBM_dataCube_expand.csv (column Var), and
  (b) one of the names in the %data_out block of that version's wbm.pl (found with the regex
      of RIMS/WBM.pm get_wbm_var_list), or ends in one of the eight per-crop suffixes that
      make_list_out accepts.
A CSV name that fails (b) aborts WBM ("does not exist in the WBM output list"), and so does a
code name that is not in the CSV ("not found in the WBM variable table"). The list is the
sorted intersection.

Usage, from web-gateway/backend (the output paths are the defaults):

    python scripts/gen_output_vars.py 23.9.0 \\
        ../../images/wbm-tools-lite/wbm/model/wbm.pl \\
        ../../images/wbm-tools-lite/wbm/model/WBM_dataCube_expand.csv

    python scripts/gen_output_vars.py 22.1.1 <wbm.pl> <WBM_dataCube_expand.csv>

WBM 22.1.1 is not in this repository. Fetch its two files from the public bucket first:

    B=https://s3.anvil.rcac.purdue.edu/openghm/wbm-code/wbm/22.1.1/model
    curl -O $B/wbm.pl -O $B/WBM_dataCube_expand.csv

The header of the output names the script and holds the sha256 of both inputs, so that a
list can be checked against the files it came from.
"""
import argparse
import hashlib
import re
import sys
from pathlib import Path

CROP = re.compile(r'(_irrigation|_irrDemand|_soilMoistFrac|_PET|_AET|_netIrrigation|_BW_ET|_GW_ET)$')
OUT_DIR = Path(__file__).resolve().parent.parent / 'app' / 'wbm_init' / 'output_vars'
SOURCES = {
    '23.9.0': 'images/wbm-tools-lite/wbm/model/',
    '22.1.1': 'https://s3.anvil.rcac.purdue.edu/openghm/wbm-code/wbm/22.1.1/model/',
}


def csv_vars(path):
    rows = [line.rstrip('\n').split('\t') for line in open(path, errors='replace')]
    var = rows[0].index('Var')
    return [r[var] for r in rows[1:] if len(r) > var and r[var]]


def code_vars(path):
    out, on = [], False
    for line in open(path, errors='replace'):
        if re.search(r"my %data_out\s*=", line):
            on = True
        if on:
            m = re.search(r"""['"](\w+)(_\$id|_\$_)*['"]\s*=>\s*\[\s*\$""", line)
            if m:
                out.append(m.group(1))
            if '### End of %data_out' in line:
                break
    return out


def sha256(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    ap.add_argument('version', choices=sorted(SOURCES), help='WBM code version')
    ap.add_argument('wbm_pl', help="that version's model/wbm.pl")
    ap.add_argument('csv', help="that version's model/WBM_dataCube_expand.csv")
    ap.add_argument('-o', '--out', help='output file (default: app/wbm_init/output_vars/<version>.txt)')
    args = ap.parse_args(argv)

    in_csv, in_code = set(csv_vars(args.csv)), set(code_vars(args.wbm_pl))
    names = sorted(n for n in in_csv if n in in_code or CROP.search(n))
    where = SOURCES[args.version]
    header = [
        f"# GENERATED by web-gateway/backend/scripts/gen_output_vars.py. Do not edit: rerun the script.",
        f"# Output_vars options for WBM {args.version}: {len(names)} names, one per line, sorted.",
        f"# Inputs, from {where}:",
        f"#   wbm.pl                    sha256 {sha256(args.wbm_pl)}",
        f"#   WBM_dataCube_expand.csv   sha256 {sha256(args.csv)}",
        f"# A name is listed if it is in the CSV 'Var' column AND in the %data_out block of wbm.pl",
        f"# (RIMS/WBM.pm get_wbm_var_list), or ends in _irrigation, _irrDemand, _soilMoistFrac, _PET,",
        f"# _AET, _netIrrigation, _BW_ET or _GW_ET (the per-crop classes, RIMS/WBM.pm make_list_out).",
        f"# Lines starting with # are comments.",
    ]
    out = Path(args.out) if args.out else OUT_DIR / f'{args.version}.txt'
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text('\n'.join(header) + '\n' + '\n'.join(names) + '\n')
    print(f'{args.version}: {len(in_csv)} CSV names, {len(in_code)} in wbm.pl, {len(names)} listed -> {out}')
    return 0


if __name__ == '__main__':
    sys.exit(main())

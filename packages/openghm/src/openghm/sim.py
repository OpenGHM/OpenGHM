"""``openghm sim submit`` — submit a WBM model run to Anvil SLURM.

Unlike the synchronous processing tools, a WBM run is asynchronous: we generate an
``sbatch`` script that runs ``singularity exec … wbm.pl`` on a compute node and
submit it with ``sbatch``.

The snapshot is a **self-describing folder**: the user points at it (defaults to the
current directory) and a ``metadata.json`` at its root declares the representative
init file and the rest of the run info. There is no snapshot registry and no
``--init`` flag.

Mount model is **split-mount** (from the job-submission testing, ``dev/
openghm_jobrun_params.md``):

- **read** (the shared snapshot, bound read-only): ``data/<data_subdir>``,
  ``data_init``, ``model``, ``utilities``, ``gdal_test_files``, plus a **per-sim
  copy** of ``wbm_init``.
- **write** (per-simulation scratch under ``<output_base>/<sim_id>/``): ``spool``,
  ``wbm_output``, ``WBM_run_state``.

The per-sim init is generated by copying the snapshot's ``wbm_init`` and rewriting
the chosen init's ``Output_dir``/``spool_dir`` to absolute container paths (v2's
``wbm_test.init`` uses a relative ``Output_dir`` that otherwise leaks output), then
applying the optional override allow-list.
"""

from __future__ import annotations

import json
import os
import posixpath
import re
from dataclasses import dataclass
from typing import List, Optional, Tuple

from .errors import OpenghmError
from .runtime import RuntimeContext, display_command
from .types import BuiltCommand, DirCopy, GeneratedFile, Mount

# ── constants (mirror dev/openghm_jobrun_params.md) ───────────────────────────
WBM_MODEL = "/wbm/model/wbm.pl"
METADATA_FILENAME = "metadata.json"

_SIM_ID_RE = re.compile(r"^[A-Za-z0-9._-]+$")
#: ``sbatch`` prints "Submitted batch job <N>" on success.
_JOBID_RE = re.compile(r"Submitted batch job (\d+)")
SIDECAR_NAME = "simulation.json"


@dataclass
class SubmitOptions:
    """Inputs for ``sim submit`` (see the CLI for flag names)."""

    #: The snapshot folder on disk. Defaults to the current directory.
    snapshot_dir: str = "."
    #: Unique simulation ID → per-sim work/output paths + init ``Output_dir``.
    simulation_id: str = ""
    # SLURM (override metadata / config defaults)
    cores: Optional[int] = None
    walltime: Optional[str] = None
    account: Optional[str] = None
    partition: Optional[str] = None
    output_base: Optional[str] = None
    # init override allow-list
    run_start: Optional[str] = None
    run_end: Optional[str] = None
    output_vars: Optional[str] = None
    spinup_start: Optional[str] = None
    spinup_end: Optional[str] = None
    spinup_loops: Optional[int] = None
    # provenance only (recorded in simulation.json, not used for submission)
    user_info: Optional[str] = None
    verbose: Optional[bool] = None


# ── metadata ──────────────────────────────────────────────────────────────────


def load_metadata(snapshot_dir: str) -> dict:
    """Read ``<snapshot_dir>/metadata.json`` (the full snapshot metadata doc)."""
    path = os.path.join(snapshot_dir, METADATA_FILENAME)
    if not os.path.isfile(path):
        raise OpenghmError(
            f"no {METADATA_FILENAME} at {snapshot_dir!r}; is this a snapshot folder? "
            f"(point sim submit at a folder containing {METADATA_FILENAME})"
        )
    try:
        with open(path, "r", encoding="utf-8") as fh:
            return json.load(fh)
    except (OSError, ValueError) as e:
        raise OpenghmError(f"cannot read {path}: {e}")


def parse_slurm_job_id(text: Optional[str]) -> Optional[str]:
    """Extract the SLURM job ID from ``sbatch`` stdout ("Submitted batch job N")."""
    if not text:
        return None
    m = _JOBID_RE.search(text)
    return m.group(1) if m else None


def sidecar_path(built: BuiltCommand) -> Optional[str]:
    """Host path of the staged ``simulation.json`` sidecar, if any."""
    for f in built.generated_files:
        if os.path.basename(f.host_path) == SIDECAR_NAME:
            return f.host_path
    return None


def record_slurm_job_id(built: BuiltCommand, job_id: str) -> Optional[str]:
    """Write ``slurm_job_id`` into the staged ``simulation.json``; return its path."""
    path = sidecar_path(built)
    if not path or not os.path.isfile(path):
        return None
    with open(path, "r", encoding="utf-8") as fh:
        data = json.load(fh)
    data["slurm_job_id"] = job_id
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(json.dumps(data, indent=2) + "\n")
    return path


def _container_version(meta: dict) -> str:
    """The WBM version, from the container the snapshot pins."""
    version = (meta.get("uses") or {}).get("container", {}).get("version")
    if not version:
        raise OpenghmError(
            "uses.container.version is missing in metadata.json "
            "(run `openghm snapshot validate` on this folder)"
        )
    return str(version)


def _derive_data_subdir(snapshot_dir: str) -> str:
    """The single subdirectory under ``<snapshot>/data/``.

    The spec has no field for this, deliberately: a snapshot bundles exactly one,
    and ADR 0015 moves ``data/`` out to a linked model input entirely.
    """
    data_dir = os.path.join(snapshot_dir, "data")
    try:
        subdirs = [d for d in os.listdir(data_dir) if os.path.isdir(os.path.join(data_dir, d))]
    except OSError:
        raise OpenghmError(f"no data/ directory under {snapshot_dir!r}")
    if len(subdirs) != 1:
        raise OpenghmError(
            f"expected exactly one subdirectory under {data_dir} (found {len(subdirs)})"
        )
    return subdirs[0]


# ── per-sim init generation ────────────────────────────────────────────────────


def _set_perl_key(content: str, key: str, value, *, quote: bool, required: bool, label: str) -> str:
    """Replace the first ``key => <value>`` in a Perl-hash init with ``value``.

    ``\\bkey\\b`` avoids matching ``Run_Start`` when replacing ``Start`` (the ``_``
    before ``Start`` is a word char, so there is no word boundary there).
    """
    repl = f"'{value}'" if quote else str(value)
    pattern = re.compile(rf"(\b{re.escape(key)}\b\s*=>\s*)(?:'[^']*'|\"[^\"]*\"|[^,}}\n]+)")
    new, n = pattern.subn(lambda m: m.group(1) + repl, content, count=1)
    if n == 0 and required:
        raise OpenghmError(f"{label}: key {key!r} not found in the init template")
    return new


def build_persim_init(template: str, simulation_id: str, opts: SubmitOptions) -> str:
    """Normalize output paths to absolute container paths, then apply overrides.

    ``Output_dir`` is always present and is the v2 relative-path leak bug, so it is
    required. ``spool_dir`` is often absent (WBM defaults spool to ``/wbm/spool/``,
    which the mount already provides), so it is only rewritten when present.
    """
    out = _set_perl_key(
        template, "Output_dir", f"/wbm/wbm_output/{simulation_id}",
        quote=True, required=True, label="normalizing Output_dir",
    )
    out = _set_perl_key(
        out, "spool_dir", "/wbm/spool/",
        quote=True, required=False, label="normalizing spool_dir",
    )
    # optional override allow-list — each raises if its key is absent
    if opts.run_start is not None:
        out = _set_perl_key(out, "Run_Start", opts.run_start, quote=True, required=True, label="--run-start")
    if opts.run_end is not None:
        out = _set_perl_key(out, "Run_End", opts.run_end, quote=True, required=True, label="--run-end")
    if opts.output_vars is not None:
        out = _set_perl_key(out, "Output_vars", opts.output_vars, quote=True, required=True, label="--output-vars")
    if opts.spinup_start is not None:
        out = _set_perl_key(out, "Start", opts.spinup_start, quote=True, required=True, label="--spinup-start")
    if opts.spinup_end is not None:
        out = _set_perl_key(out, "End", opts.spinup_end, quote=True, required=True, label="--spinup-end")
    if opts.spinup_loops is not None:
        out = _set_perl_key(out, "Loops", opts.spinup_loops, quote=False, required=True, label="--spinup-loops")
    return out


# ── singularity/apptainer argv (plain exec — WBM needs env/home; no -c/-e) ─────


def _wbm_exec_argv(ctx: RuntimeContext, mounts: List[Mount], inner_cmd: List[str]) -> List[str]:
    binds: List[str] = []
    is_docker = ctx.runtime == "docker"
    flag = "-v" if is_docker else "-B"
    for m in mounts:
        binds.append(flag)
        binds.append(f"{m.host}:{m.container}:ro" if m.readonly else f"{m.host}:{m.container}")
    if is_docker:
        return ["docker", "run", "--rm", *binds, ctx.image, *inner_cmd]
    return [ctx.runtime, "exec", *binds, ctx.image, *inner_cmd]


def _render_sbatch(
    *, sim_id: str, account: str, partition: str, cores: int, walltime: str,
    workdir: str, exec_line: str,
) -> str:
    return "\n".join([
        "#!/bin/bash",
        f"#SBATCH --job-name=wbm-{sim_id}",
        f"#SBATCH --account={account}",
        f"#SBATCH --partition={partition}",
        f"#SBATCH --cpus-per-task={cores}",
        f"#SBATCH --time={walltime}",
        f"#SBATCH --output={workdir}/slurm-%j.out",
        f"#SBATCH --error={workdir}/slurm-%j.err",
        "",
        "set -euo pipefail",
        "",
        exec_line,
        "",
    ])


# ── main builder ────────────────────────────────────────────────────────────


@dataclass
class _Resolved:
    """Everything ``sim submit`` and ``sim run`` share once a snapshot is resolved.

    The only difference between the two commands is the last wrapping layer:
    submit emits an sbatch script and runs ``sbatch``; run runs the container
    exec directly in the foreground. Both build on this.
    """

    ctx: RuntimeContext
    mounts: List[Mount]
    inner_cmd: List[str]
    exec_argv: List[str]
    exec_line: str
    workdir: str
    spool_dir: str
    output_dir: str
    run_state_dir: str
    persim_wbm_init: str
    init_filename: str
    persim_init_content: str
    snap: str
    version: str
    data_subdir: str
    cores: int
    walltime: str
    account: str
    partition: str
    output_base: str


def _resolve_run(
    opts: SubmitOptions,
    config,
    *,
    runtime: Optional[str] = None,
    sif: Optional[str] = None,
) -> _Resolved:
    """Resolve a snapshot folder + metadata into the shared plan for submit/run."""
    sim_id = opts.simulation_id
    if not sim_id or not _SIM_ID_RE.match(sim_id):
        raise OpenghmError("--id is required and must match [A-Za-z0-9._-]+")

    snap = os.path.abspath(opts.snapshot_dir)
    if not os.path.isdir(snap):
        raise OpenghmError(f"snapshot folder not found: {snap}")

    meta = load_metadata(snap)
    simulation = meta.get("simulation")
    if not isinstance(simulation, dict):
        raise OpenghmError(
            f"{METADATA_FILENAME} has no simulation block; it does not follow the "
            "snapshot spec (run `openghm snapshot validate` on this folder)"
        )

    init_filename = simulation.get("init")
    if not init_filename:
        raise OpenghmError("simulation.init is missing in metadata.json")
    init_template_path = os.path.join(snap, "wbm_init", init_filename)
    if not os.path.isfile(init_template_path):
        raise OpenghmError(f"init file not found: {init_template_path}")

    version = _container_version(meta)
    # No spec field: a snapshot's data/ has exactly one subdirectory, and
    # ADR 0015 moves data/ out to a linked model input, at which point the
    # question goes away rather than needing one.
    data_subdir = _derive_data_subdir(snap)

    # The spec requires both, so there is nothing to fall back to. --cores and
    # --walltime still override; that is a user's choice, not a default.
    compute = simulation.get("recommendedCompute") or {}
    cores = opts.cores or compute.get("cores")
    walltime = opts.walltime or compute.get("walltime")
    if not cores or not walltime:
        raise OpenghmError(
            "simulation.recommendedCompute must set both cores and walltime "
            "(run `openghm snapshot validate` on this folder)"
        )
    account = opts.account or config.account
    partition = opts.partition or config.partition
    output_base = opts.output_base or config.resolve_output_base()

    image = sif or config.resolve_wbm_sif(version)
    ctx = RuntimeContext(runtime=runtime or config.runtime, image=image)

    # per-sim host paths
    workdir = posixpath.join(output_base, sim_id)
    persim_wbm_init = posixpath.join(workdir, "wbm_init")
    spool_dir = posixpath.join(workdir, "spool")
    output_dir = posixpath.join(workdir, "wbm_output")
    run_state_dir = posixpath.join(workdir, "WBM_run_state")

    # split mounts: read (snapshot, :ro) + write (per-sim scratch)
    mounts = [
        Mount(posixpath.join(snap, "data", data_subdir), "/wbm/data", True),
        Mount(posixpath.join(snap, "data_init"), "/wbm/data_init", True),
        Mount(spool_dir, "/wbm/spool", False),
        Mount(output_dir, "/wbm/wbm_output", False),
        Mount(run_state_dir, "/wbm/WBM_run_state", False),
        Mount(persim_wbm_init, "/wbm/wbm_init", False),
        Mount(posixpath.join(snap, "model"), "/wbm/model", True),
        Mount(posixpath.join(snap, "utilities"), "/wbm/utilities", True),
        Mount(posixpath.join(snap, "gdal_test_files"), "/wbm/gdal_test_files", True),
    ]

    inner_cmd = [WBM_MODEL, *(["-v"] if opts.verbose else []), f"/wbm/wbm_init/{init_filename}"]
    exec_argv = _wbm_exec_argv(ctx, mounts, inner_cmd)
    persim_init_content = build_persim_init(
        open(init_template_path, "r", encoding="utf-8").read(), sim_id, opts
    )

    return _Resolved(
        ctx=ctx, mounts=mounts, inner_cmd=inner_cmd, exec_argv=exec_argv,
        exec_line=display_command(exec_argv), workdir=workdir, spool_dir=spool_dir,
        output_dir=output_dir, run_state_dir=run_state_dir, persim_wbm_init=persim_wbm_init,
        init_filename=init_filename, persim_init_content=persim_init_content, snap=snap,
        version=version, data_subdir=data_subdir, cores=cores, walltime=walltime,
        account=account, partition=partition, output_base=output_base,
    )


def _base_sidecar(r: _Resolved, opts: SubmitOptions, sim_id: str, now: Optional[str]) -> dict:
    """Provenance fields common to submit and run (mode-specific keys added by caller)."""
    return {
        "simulation_id": sim_id,
        "snapshot": os.path.basename(os.path.normpath(r.snap)),
        "snapshot_path": r.snap,
        "init": r.init_filename,
        "wbm_version": r.version,
        "data_subdir": r.data_subdir,
        "cores": r.cores,
        "walltime": r.walltime,
        "account": r.account,
        "partition": r.partition,
        "user_info": opts.user_info,
        "submitted_at": now,
    }


def _persim_files(r: _Resolved) -> Tuple[GeneratedFile, DirCopy, List[str]]:
    """The per-sim init file + wbm_init copy + scratch dirs shared by both modes."""
    init_file = GeneratedFile(
        posixpath.join(r.persim_wbm_init, r.init_filename), r.persim_init_content
    )
    copy = DirCopy(posixpath.join(r.snap, "wbm_init"), r.persim_wbm_init)
    dirs = [r.spool_dir, r.output_dir, r.run_state_dir]
    return init_file, copy, dirs


def build_submit(
    opts: SubmitOptions,
    config,
    *,
    runtime: Optional[str] = None,
    sif: Optional[str] = None,
    now: Optional[str] = None,
) -> Tuple[RuntimeContext, BuiltCommand]:
    """Resolve a snapshot folder + metadata into a ready-to-submit sbatch job."""
    r = _resolve_run(opts, config, runtime=runtime, sif=sif)
    init_file, copy, dirs = _persim_files(r)

    sbatch_content = _render_sbatch(
        sim_id=opts.simulation_id, account=r.account, partition=r.partition, cores=r.cores,
        walltime=r.walltime, workdir=r.workdir, exec_line=r.exec_line,
    )
    sidecar = _base_sidecar(r, opts, opts.simulation_id, now)
    sidecar["mode"] = "slurm"
    sidecar["slurm_job_id"] = None

    sbatch_path = posixpath.join(r.workdir, f"submit_{opts.simulation_id}.sbatch")
    generated = [
        init_file,
        GeneratedFile(sbatch_path, sbatch_content),
        GeneratedFile(posixpath.join(r.workdir, "simulation.json"),
                      json.dumps(sidecar, indent=2) + "\n"),
    ]

    built = BuiltCommand(
        argv=["sbatch", sbatch_path],
        mounts=r.mounts,
        inner_cmd=r.inner_cmd,
        generated_files=generated,
        staged_dirs=dirs,
        staged_copies=[copy],
        display=display_command(["sbatch", sbatch_path]),
    )
    return r.ctx, built


def build_run(
    opts: SubmitOptions,
    config,
    *,
    runtime: Optional[str] = None,
    sif: Optional[str] = None,
    now: Optional[str] = None,
) -> Tuple[RuntimeContext, BuiltCommand]:
    """Resolve a snapshot into a foreground local run (container exec, no SLURM).

    Same snapshot/metadata/split-mount machinery as :func:`build_submit`, but the
    argv is the container ``exec`` line itself — no sbatch script is generated and
    the job runs synchronously on this machine.
    """
    r = _resolve_run(opts, config, runtime=runtime, sif=sif)
    init_file, copy, dirs = _persim_files(r)

    sidecar = _base_sidecar(r, opts, opts.simulation_id, now)
    sidecar["mode"] = "local"
    sidecar["exit_code"] = None  # filled in by record_exit_code after the run

    generated = [
        init_file,
        GeneratedFile(posixpath.join(r.workdir, "simulation.json"),
                      json.dumps(sidecar, indent=2) + "\n"),
    ]

    built = BuiltCommand(
        argv=r.exec_argv,
        mounts=r.mounts,
        inner_cmd=r.inner_cmd,
        generated_files=generated,
        staged_dirs=dirs,
        staged_copies=[copy],
        display=r.exec_line,
    )
    return r.ctx, built


def record_exit_code(built: BuiltCommand, exit_code: int) -> Optional[str]:
    """Write ``exit_code`` into a local run's staged ``simulation.json``; return its path."""
    path = sidecar_path(built)
    if not path or not os.path.isfile(path):
        return None
    with open(path, "r", encoding="utf-8") as fh:
        data = json.load(fh)
    data["exit_code"] = exit_code
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(json.dumps(data, indent=2) + "\n")
    return path


# ── management: list / status / logs / cancel ─────────────────────────────────
#
# These operate on the per-sim ``simulation.json`` sidecars under ``output_base``
# and on SLURM (``sacct``/``scancel``), not on snapshots — so they do not fit the
# container ``BuiltCommand`` model. They are local queries/actions: the pure,
# testable parts (sidecar reading, id resolution, argv building, sacct/log
# parsing) live here; the CLI runs the subprocess and renders the result.

#: ``sacct`` columns requested by :func:`build_sacct_argv`, in output order.
SACCT_FIELDS = ("JobID", "JobName", "State", "ExitCode", "Elapsed", "Start", "End", "Partition", "AllocCPUS")


def read_sidecar(path: str) -> dict:
    """Load one ``simulation.json`` sidecar (raises ``OpenghmError`` if unreadable)."""
    try:
        with open(path, "r", encoding="utf-8") as fh:
            return json.load(fh)
    except (OSError, ValueError) as e:
        raise OpenghmError(f"cannot read {path}: {e}")


def list_simulations(output_base: str) -> List[dict]:
    """Every ``<output_base>/*/simulation.json``, newest first.

    Each record is the sidecar content plus ``_dir`` (its per-sim work directory).
    A missing/unreadable ``output_base`` yields an empty list (nothing submitted
    yet); an individual unreadable sidecar is skipped rather than fatal.
    """
    try:
        names = sorted(os.listdir(output_base))
    except OSError:
        return []
    records: List[dict] = []
    for name in names:
        sc = os.path.join(output_base, name, SIDECAR_NAME)
        if not os.path.isfile(sc):
            continue
        try:
            rec = read_sidecar(sc)
        except OpenghmError:
            continue
        rec["_dir"] = os.path.join(output_base, name)
        records.append(rec)
    records.sort(key=lambda r: (r.get("submitted_at") or ""), reverse=True)
    return records


def find_simulation(output_base: str, key: str) -> Optional[dict]:
    """Locate a simulation by its ID (directory name) or SLURM job ID (scan).

    Returns the sidecar record (with ``_dir``) or ``None``. A direct directory
    match is preferred; otherwise every sidecar's ``slurm_job_id`` is checked.
    """
    direct = os.path.join(output_base, key, SIDECAR_NAME)
    if os.path.isfile(direct):
        rec = read_sidecar(direct)
        rec["_dir"] = os.path.join(output_base, key)
        return rec
    for rec in list_simulations(output_base):
        if str(rec.get("slurm_job_id")) == key:
            return rec
    return None


def resolve_job_id(output_base: str, key: str) -> Tuple[str, Optional[dict]]:
    """Map ``key`` (a sim ID or a raw numeric job ID) to a SLURM job ID.

    Returns ``(job_id, sidecar_or_None)``. Raises if a known sim has no recorded
    job id, or if ``key`` is neither a known sim nor a numeric job id.
    """
    rec = find_simulation(output_base, key)
    if rec is not None:
        if rec.get("mode") == "local":
            raise OpenghmError(
                f"simulation {rec.get('simulation_id', key)!r} was run locally "
                "(synchronous); there is no SLURM job to query or cancel"
            )
        job_id = rec.get("slurm_job_id")
        if not job_id:
            raise OpenghmError(
                f"simulation {rec.get('simulation_id', key)!r} has no recorded SLURM "
                "job id (not submitted yet, or the submit failed)"
            )
        return str(job_id), rec
    if key.isdigit():
        return key, None
    raise OpenghmError(
        f"no simulation {key!r} under {output_base} (and it is not a numeric job id)"
    )


def build_sacct_argv(job_id: str) -> List[str]:
    """``sacct`` argv for one job: pipe-delimited, headerless (see :func:`parse_sacct`)."""
    return ["sacct", "-j", str(job_id), "-P", "--noheader", "--format=" + ",".join(SACCT_FIELDS)]


def parse_sacct(text: Optional[str]) -> List[dict]:
    """Parse ``sacct -P --noheader`` output into one dict per row (keyed by ``SACCT_FIELDS``)."""
    rows: List[dict] = []
    for line in (text or "").splitlines():
        line = line.strip()
        if not line:
            continue
        parts = line.split("|")
        rows.append({f: (parts[i] if i < len(parts) else "") for i, f in enumerate(SACCT_FIELDS)})
    return rows


def sacct_primary(rows: List[dict], job_id: str) -> Optional[dict]:
    """The headline row (``JobID`` == ``job_id``), not a ``.batch``/``.extern`` step."""
    for r in rows:
        if r.get("JobID") == str(job_id):
            return r
    return rows[0] if rows else None


def build_scancel_argv(job_id: str) -> List[str]:
    """``scancel`` argv for one job."""
    return ["scancel", str(job_id)]


def slurm_log_path(sim_dir: str, job_id: str, *, err: bool = False) -> str:
    """``<sim_dir>/slurm-<job_id>.out`` (or ``.err``) — matches the sbatch directives."""
    return os.path.join(sim_dir, f"slurm-{job_id}.{'err' if err else 'out'}")


def tail_lines(path: str, n: int) -> List[str]:
    """Last ``n`` lines of ``path`` (``n <= 0`` → all). Raises if the file is absent."""
    if not os.path.isfile(path):
        raise OpenghmError(f"log not found: {path} (job may not have started, or wrong stream)")
    with open(path, "r", encoding="utf-8", errors="replace") as fh:
        lines = fh.read().splitlines()
    return lines if n <= 0 else lines[-n:]
